// Service worker BCA Admin: menyimpan "cangkang" aplikasi supaya bisa dibuka
// cepat dan tetap menampilkan pesan saat offline. Data kiriman TIDAK pernah
// disimpan di sini — dashboard tetap dimuat langsung dari Google.
const CACHE = 'bca-admin-v5';
const SHELL = [
  './',
  './index.html',
  './manifest.webmanifest',
  './icons/icon-192.png',
  './icons/icon-512.png',
  './icons/maskable-512.png',
  './icons/apple-touch-icon.png',
  './icons/adit-240.jpg'
];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return; // Google: selalu lewat jaringan

  // Halaman: coba jaringan dulu (supaya update cepat), kalau offline pakai cache.
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('./index.html', copy));
          return res;
        })
        .catch(() => caches.match('./index.html'))
    );
    return;
  }
  // Ikon & manifest: cache dulu.
  event.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
